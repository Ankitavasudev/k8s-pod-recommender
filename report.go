// renderHTML renders the recommendations as a self-contained page.
func renderHTML(recs []recommender.Recommendation) (string, error) {
	counts := make([]actionCount, 0, len(actionOrder))
	for _, action := range actionOrder {
		count := 0
		for _, rec := range recs {
			if rec.Action == action {
				count++
			}
		}
		counts = append(counts, actionCount{Action: action, Count: count})
	}

	var b strings.Builder
	err := reportTemplate.Execute(&b, reportData{
		Generated: time.Now().Format("2006-01-02 15:04 MST"),
		Version:   versionString(),
		Total:     len(recs),
		Counts:    counts,
		Recs:      recs,
	})
	if err != nil {
		return "", err
	}
	return strings.TrimSuffix(b.String(), "\n"), nil
}
